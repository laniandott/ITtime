import 'fake-indexeddb/auto'
import { test } from 'node:test'
import assert from 'node:assert/strict'

Object.defineProperty(globalThis, 'self', { value: globalThis, configurable: true })
const { localRequest, localDatabase } = await import('../src/localData.ts')
const { default: PouchDB } = await import('pouchdb-browser')
test('two activities persist independently and stopping one retains the other', async () => {
  const post = (path: string, body: unknown = {}) => localRequest<any>(path, { method: 'POST', body: JSON.stringify(body) })
  const legacy = new PouchDB<any>('ittime-tagtime-v1')
  await legacy.put({ _id: 'categories:legacy', entity: 'categories', value: { id: 'legacy', name: '旧分类' }, updatedAt: new Date().toISOString() })
  try {
    assert.equal((await localRequest<any[]>('/categories')).some(category => category.id === 'legacy'), true)
    const firstTag = await post('/tags', { name: '项目一' })
    const secondTag = await post('/tags', { name: '项目二' })
    const first = await post('/timer/start', { tagId: firstTag.id })
    const second = await post('/timer/start', { tagId: secondTag.id })
    assert.equal((await localRequest<any>('/timer/current')).running.length, 2)
    const stopped = await post(`/timer/stop/${first.id}`)
    assert.ok(stopped.endTime)
    const current = await localRequest<any>('/timer/current')
    assert.deepEqual(current.running.map((entry: any) => entry.id), [second.id])
    const records = await localRequest<any[]>('/timer')
    assert.equal(records.length, 2)
    assert.equal(records.find(entry => entry.id === first.id)?.tag.name, '项目一')
    const goal = await post('/goals', { tagId: firstTag.id, title: '每日项目一', kind: 'activity', period: 'daily' })
    const weeklyGoal = await post('/goals', { tagId: secondTag.id, title: '每周项目二', kind: 'activity', period: 'weekly', deadlineTime: '18:30' })
    const generated = await localRequest<any[]>('/todos')
    assert.equal(generated.filter(todo => todo.goalId === goal.id).length, 1)
    const weekly = generated.find(todo => todo.goalId === weeklyGoal.id)
    assert.ok(weekly)
    assert.equal(weekly.repeatType, 'weekly')
    const weeklyDeadline = new Date(weekly.dueDate)
    assert.equal(weeklyDeadline.getDay(), 0)
    assert.equal(weeklyDeadline.getHours(), 18)
    assert.equal(weeklyDeadline.getMinutes(), 30)
    assert.equal((await localRequest<any[]>('/todos')).length, generated.length)
    const activity = generated.find(todo => todo.goalId === goal.id)!
    await localRequest(`/todos/${activity.id}/toggle`, { method: 'PATCH', body: '{}' })
    assert.equal((await localRequest<any[]>('/todos?status=pending')).filter(todo => todo.goalId === goal.id).length, 0)
    assert.equal((await localRequest<any[]>('/goals')).find(rule => rule.id === goal.id)?.current, 1)
    const timeGoal = await post('/goals', { tagId: firstTag.id, title: '每日专注时长', kind: 'tracking', type: 'time', target: 60, period: 'daily' })
    await post('/timer/start', { tagId: firstTag.id, startTime: new Date(Date.now() - 120_000).toISOString() })
    assert.equal((await localRequest<any[]>('/goals')).find(rule => rule.id === timeGoal.id)?.current, 2)
    const chaosEntry = await post('/timer/start', { tagId: firstTag.id })
    const chaosStopped = await post(`/timer/stop/${chaosEntry.id}`, { pendingResume: true, note: '不应进入待续' })
    assert.equal(chaosStopped.pendingResume, false)
    const orderedTag = await post('/tags', { name: '有序项目', mode: 'ordered' })
    const orderedEntry = await post('/timer/start', { tagId: orderedTag.id })
    await assert.rejects(post(`/timer/stop/${orderedEntry.id}`, { pendingResume: true }), /必须填写/)
    const pausedEntry = await post(`/timer/stop/${orderedEntry.id}`, { pendingResume: true, note: '下一步继续整理' })
    assert.equal(pausedEntry.pendingResume, true)
    await assert.rejects(post('/timer/manual', { tagId: firstTag.id, startTime: 'invalid', endTime: 'invalid' }), /不是有效时间/)
    await assert.rejects(post('/timer/manual', { tagId: firstTag.id, startTime: '2026-01-01T10:00:00Z', endTime: '2026-01-01T09:00:00Z' }), /必须晚于/)
    const manual = await post('/timer/manual', { tagId: firstTag.id, startTime: '2026-01-01T10:00:00Z', endTime: '2026-01-01T10:30:00Z' })
    assert.equal(manual.startTime, '2026-01-01T10:00:00Z')
    await assert.rejects(localRequest(`/timer/${manual.id}`, { method: 'PUT', body: JSON.stringify({ startTime: 'invalid' }) }), /startTime 不是有效时间/)
    await assert.rejects(localRequest(`/timer/${manual.id}`, { method: 'PUT', body: JSON.stringify({ startTime: '2026-01-01T11:00:00Z', endTime: '2026-01-01T10:00:00Z' }) }), /结束时间不能早于/)
    await assert.rejects(localRequest(`/timer/${manual.id}`, { method: 'PUT', body: JSON.stringify({ tagId: 'missing-tag' }) }), (error: any) => error.status === 404)
    const edited = await localRequest<any>(`/timer/${manual.id}`, { method: 'PUT', body: JSON.stringify({ note: '已修正' }) })
    assert.equal(edited.note, '已修正')
    const onceGoal = await post('/goals', { tagId: firstTag.id, title: '一次性项目', kind: 'activity', period: 'once', deadlineAt: new Date().toISOString() })
    const onceTodo = (await localRequest<any[]>('/todos')).find(todo => todo.goalId === onceGoal.id)!
    const onceDoc = await localDatabase().get(`todos:${onceTodo.id}`)
    await localDatabase().put({ ...onceDoc, value: { ...onceDoc.value, status: 'done', completedAt: new Date(Date.now() - 86_400_000).toISOString() } })
    assert.equal((await localRequest<any[]>('/goals')).find(rule => rule.id === onceGoal.id)?.current, 1)
    const chainRoot = await post('/timer/start', { tagId: firstTag.id })
    await post(`/timer/stop/${chainRoot.id}`, { pendingResume: true, note: '稍后继续' })
    const chainChild = await post('/timer/start', { tagId: secondTag.id, interruptedFromId: chainRoot.id })
    await assert.rejects(post(`/timer/${chainChild.id}/terminate-chain`, { reason: ' ' }), /必须填写/)
    await assert.rejects(post(`/timer/${chainChild.id}/terminate-chain`, { reason: 'x'.repeat(1_001) }), /不能超过 1000/)
    const terminated = await post(`/timer/${chainChild.id}/terminate-chain`, { reason: '今天不再继续' })
    assert.equal(terminated.count, 2)
    const terminatedRoot = await localRequest<any>(`/timer/${chainRoot.id}`)
    const terminatedChild = await localRequest<any>(`/timer/${chainChild.id}`)
    assert.equal(terminatedRoot.dismissed, true)
    assert.equal(terminatedRoot.pendingResume, false)
    assert.equal(terminatedChild.dismissReason, '今天不再继续')
    const orderCategory = await post('/categories', { name: '顺序测试分类' })
    const tagA = await post('/tags', { name: '顺序测试A', categoryId: orderCategory.id, sortOrder: 0 })
    const tagB = await post('/tags', { name: '顺序测试B', categoryId: orderCategory.id, sortOrder: 10 })
    await localRequest(`/tags/${tagA.id}`, { method: 'PUT', body: JSON.stringify({ sortOrder: 20 }) })
    await localRequest(`/tags/${tagB.id}`, { method: 'PUT', body: JSON.stringify({ sortOrder: 0 }) })
    assert.deepEqual((await localRequest<any[]>('/tags')).filter(tag => tag.categoryId === orderCategory.id).map(tag => tag.id), [tagB.id, tagA.id])
    const deletedCategory = await post('/categories', { name: '本地逻辑删除测试' })
    await localRequest(`/categories/${deletedCategory.id}`, { method: 'DELETE' })
    assert.equal((await localRequest<any[]>('/categories')).some(category => category.id === deletedCategory.id), false)
    await assert.rejects(localRequest(`/categories/${deletedCategory.id}`), (error: any) => error.status === 404)
    assert.ok((await localDatabase().get(`categories:${deletedCategory.id}`)).deletedAt)

    const planDate = new Date().toISOString().slice(0, 10)
    const plan = await post('/plans', { date: planDate, startMinute: 9 * 60, endMinute: 10 * 60, content: '整理计划功能', tagId: firstTag.id })
    assert.equal(plan.content, '整理计划功能')
    const overlappingPlan = await post('/plans', { date: planDate, startMinute: 9 * 60 + 30, endMinute: 10 * 60 + 30, content: '并行计划' })
    assert.equal(overlappingPlan.content, '并行计划')
    const linkedTodo = await post('/todos', { title: '保持已完成关联', tagId: firstTag.id })
    const linkedPlan = await post('/plans', { date: planDate, startMinute: 10 * 60 + 30, endMinute: 11 * 60, content: '完成待办后仍保留关联', todoId: linkedTodo.id })
    await localRequest(`/todos/${linkedTodo.id}/toggle`, { method: 'PATCH', body: '{}' })
    const linkedPlanAfterTodoCompletion = await localRequest<any>(`/plans/${linkedPlan.id}`)
    assert.equal(linkedPlanAfterTodoCompletion.todoId, linkedTodo.id)
    assert.equal(linkedPlanAfterTodoCompletion.todo.status, 'done')
    await assert.rejects(post('/plans', { date: planDate, startMinute: 10 * 60, endMinute: 11 * 60, content: '   ' }), /不能为空/)
    const plannedEntry = await post('/timer/start', { tagId: firstTag.id, planId: plan.id, note: plan.content })
    assert.equal(plannedEntry.planId, plan.id)
    await post(`/timer/stop/${plannedEntry.id}`)
    const loadedPlan = await localRequest<any>(`/plans/${plan.id}`)
    assert.ok(loadedPlan.actualMs >= 0)
    const orderedPlan = await post('/plans', { date: planDate, startMinute: 11 * 60, endMinute: 12 * 60, content: '继续有序任务', tagId: orderedTag.id })
    const pendingPlanEntry = await post('/timer/start', { tagId: orderedTag.id, planId: orderedPlan.id })
    await post(`/timer/stop/${pendingPlanEntry.id}`, { pendingResume: true, note: '稍后继续' })
    const resumedPlanEntry = await post('/timer/start', { tagId: orderedTag.id, resumedFromId: pendingPlanEntry.id })
    assert.equal(resumedPlanEntry.planId, orderedPlan.id)
    const interruptedRoot = await post('/timer/start', { tagId: firstTag.id, planId: plan.id })
    const interruptedChild = await post('/timer/start', { tagId: secondTag.id, interruptedFromId: interruptedRoot.id })
    assert.equal(interruptedChild.planId, null)
    const deferred = await post(`/plans/${plan.id}/defer`, { date: planDate, startMinute: 13 * 60, endMinute: 14 * 60 })
    assert.equal(deferred.deferredFromId, plan.id)
    const deferredAgain = await post(`/plans/${plan.id}/defer`, { date: planDate, startMinute: 13 * 60, endMinute: 14 * 60 })
    assert.equal(deferredAgain.id, deferred.id)
    await assert.rejects(localRequest(`/plans/${plan.id}`, { method: 'DELETE' }), /推迟链路/)
  } finally { await localDatabase().destroy(); await legacy.destroy() }
})
